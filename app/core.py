def sync_ledger_splits(reference_type: str, reference_id: int, branch_id: int, transaction_type: str, direction: str, total_amount: float, transaction_date: str, notes: str, created_by: int, splits: list[tuple[int, float]]) -> None:
    db = get_db()
    clean = [(int(account_id), round(float(value), 2)) for account_id, value in splits if float(value) > 0]
    if not clean:
        raise ValueError("يجب تحديد حساب مالي واحد على الأقل.")
    split_total = round(sum(value for _, value in clean), 2)
    if round(float(total_amount), 2) != split_total:
        raise ValueError(f"مجموع التقسيم ({split_total:.2f}) لا يساوي قيمة العملية ({float(total_amount):.2f}).")
    valid_ids = {row["id"] for row in db.execute("SELECT id FROM financial_accounts WHERE branch_id=? AND is_active=1", (branch_id,)).fetchall()}
    if any(account_id not in valid_ids for account_id, _ in clean):
        raise ValueError("أحد الحسابات المالية غير صالح لهذا الفرع.")
    db.execute("DELETE FROM financial_ledger WHERE reference_type=? AND reference_id=?", (reference_type, reference_id))
    prefix = {"REVENUE":"REV", "EXPENSE":"EXP", "SUPPLIER_PAYMENT":"PAY", "EXTERNAL_DEBT":"EXTD", "EXTERNAL_DEBT_PAYMENT":"EXTP"}.get(transaction_type, "TXN")
    for index, (account_id, value) in enumerate(clean, 1):
        txno = f"TXN-{prefix}-{reference_id:06d}-{index:02d}"
        db.execute("""INSERT INTO financial_ledger(transaction_number,branch_id,account_id,transaction_type,direction,amount,transaction_date,reference_type,reference_id,notes,created_by,created_at)
                      VALUES(?,?,?,?,?,?,?,?,?,?,?,?)""",
                   (txno, branch_id, account_id, transaction_type, direction, value, transaction_date, reference_type, reference_id, notes, created_by, now()))


def parse_account_splits(form, branch_id: int, total_amount: float) -> list[tuple[int, float]]:
    account_ids = form.getlist("split_account_id")
    amounts = form.getlist("split_amount")
    if not account_ids:
        account_id = form.get("account_id", type=int)
        if not account_id:
            row = get_db().execute("SELECT id FROM financial_accounts WHERE branch_id=? AND is_active=1 ORDER BY CASE account_type WHEN 'CASH' THEN 0 ELSE 1 END,id LIMIT 1", (branch_id,)).fetchone()
            account_id = row["id"] if row else None
        return [(account_id, total_amount)] if account_id else []
    splits = []
    for raw_account, raw_amount in zip(account_ids, amounts):
        if not raw_account or not raw_amount:
            continue
        value = float(raw_amount)
        if value > 0:
            splits.append((int(raw_account), value))
    return splits


