def has_permission(permission: str) -> bool:
    """Check permissions with a request-local cache to avoid duplicate SQL."""
    cache = getattr(g, "_permission_cache", None)
    if cache is None:
        cache = {}
        g._permission_cache = cache
    if permission in cache:
        return cache[permission]

    user = current_user()
    allowed = False
    if user and user["is_active"]:
        if user["role"] == "admin":
            allowed = True
        else:
            row = get_db().execute(
                "SELECT 1 FROM user_permissions WHERE user_id = ? AND permission = ?",
                (user["id"], permission),
            ).fetchone()
            if row is not None:
                allowed = True
            elif "role_id" in user.keys() and user["role_id"]:
                row = get_db().execute(
                    "SELECT 1 FROM role_permissions WHERE role_id=? AND permission=?",
                    (user["role_id"], permission),
                ).fetchone()
                allowed = row is not None

    cache[permission] = allowed
    return allowed


def login_required(view: Callable[..., Any]) -> Callable[..., Any]:
    @wraps(view)
    def wrapped(*args: Any, **kwargs: Any) -> Any:
        if not current_user():
            return redirect(url_for("login"))
        return view(*args, **kwargs)

    return wrapped


def permission_required(permission: str) -> Callable[[Callable[..., Any]], Callable[..., Any]]:
    def decorator(view: Callable[..., Any]) -> Callable[..., Any]:
        @wraps(view)
        def wrapped(*args: Any, **kwargs: Any) -> Any:
            if not has_permission(permission):
                flash("ليس لديك صلاحية لتنفيذ هذه العملية.", "danger")
                return redirect(url_for("dashboard"))
            return view(*args, **kwargs)

        return wrapped

    return decorator


