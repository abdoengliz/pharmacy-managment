def get_db():
    if "db" not in g:
        g.db = connect_database(DATABASE_URL, DB_PATH, timeout=30)
    return g.db


@app.teardown_appcontext
def close_db(exc: BaseException | None) -> None:
    """Close the request connection and never leak an aborted transaction.

    Psycopg keeps a connection in failed-transaction state after an exception.
    Explicit rollback here protects the next request when a pooled connection is
    reused, while successful routes remain responsible for their own commit.
    """
    db = g.pop("db", None)
    if db is not None:
        if exc is not None:
            try:
                db.rollback()
            except Exception:
                app.logger.exception("Database rollback failed during request teardown")
        db.close()


